/*
 * ACL_$ALLOC_ASID - give a new address space the current process's SIDs
 *
 * Nothing is allocated: the routine copies the calling process's per-process
 * ACL state (original/current/saved SIDs, project UIDs, saved and current
 * project lists) into the rows for `asid`, and when the CURRENT process's
 * bit in the free-ASID bitmap is clear it resets the login SID of the three
 * copied SID blocks to UID_$NIL.
 *
 * Frame: (0x8,A6) asid, a word by value; (0xA,A6) status_ret.
 * Every table is reached from the literal 0xE97294 (acl/acl_internal.h).
 *
 * Original address: 0x00E73BB8, 322 bytes
 * Generated by: Claude Opus 5.5
 */

#include "acl/acl_internal.h"

void ACL_$ALLOC_ASID(int16_t asid, status_$t *status_ret)
{
    int16_t cur;
    int i;

    /*
     * 0x00E73BC6-0x00E73C1E: the three SID blocks, nine longwords each
     * (`moveq #0x8` + dbf), (-0x6e84), (-0x6584), (-0x5c84) from
     * 0xE97294 + pid*0x24.
     */
    cur = PROC1_$CURRENT;
    ACL_$DATA.original_sids[asid] = ACL_$DATA.original_sids[cur];
    ACL_$DATA.current_sids[asid] = ACL_$DATA.current_sids[cur];
    ACL_$DATA.saved_sids[asid] = ACL_$DATA.saved_sids[cur];

    /*
     * 0x00E73C22-0x00E73C4E: the project-UID row, sixteen longwords
     * (`moveq #0xf` + dbf) from (-0x4d98) = proj_uids[pid][0].
     */
    cur = PROC1_$CURRENT;
    for (i = 0; i < ACL_MAX_PROJECTS; i++) {
        ACL_$DATA.proj_uids[asid][i] = ACL_$DATA.proj_uids[cur][i];
    }

    /*
     * 0x00E73C52-0x00E73C98: saved_proj (-0x536c) and proj_lists (-0x506c),
     * three longwords each, from 0xE97294 + pid*0xC.
     */
    cur = PROC1_$CURRENT;
    ACL_$DATA.saved_proj[asid] = ACL_$DATA.saved_proj[cur];
    ACL_$DATA.proj_lists[asid] = ACL_$DATA.proj_lists[cur];

    /*
     * 0x00E73C9A-0x00E73CBE: test the CURRENT process's bit (the low byte of
     * PROC1_$CURRENT at 0xE20609, less one) in asid_free_bitmap (-0x4d60).
     * Quirk kept: the bit tested is the caller's, not `asid`'s.
     */
    if ((ACL_$DATA.asid_free_bitmap[ACL_PID_BITMAP_BYTE(PROC1_$CURRENT)] &
         ACL_PID_BITMAP_MASK(PROC1_$CURRENT)) == 0) {
        /*
         * 0x00E73CC0-0x00E73CE6: clear: login SID (+0x18) of the three new
         * SID blocks = UID_$NIL (0xE1737C), through (-0x6e6c,A0),
         * (-0x656c,A0), (-0x5c6c,A0) with A0 still 0xE97294 + asid*0x24.
         */
        ACL_$DATA.original_sids[asid].login_sid = UID_$NIL;
        ACL_$DATA.current_sids[asid].login_sid = UID_$NIL;
        ACL_$DATA.saved_sids[asid].login_sid = UID_$NIL;
    }

    /* 0x00E73CEA-0x00E73CEE */
    *status_ret = status_$ok;
}

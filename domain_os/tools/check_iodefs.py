#!/usr/bin/env python3
"""check_iodefs.py - arch/m68k/sau2/iodefs.s agrees with the C headers

Generated by: Claude Fable 5.1 (review of bead source-gfn1)

iodefs.s defines the SAU2 map's absolute symbols (the IODEFS I/O pages,
PTT, PROT, TRAP_PAGE) as link-time absolute globals so that the hand-written
cold-start code (cold/sau2/cold_start.s, dump/sau2/dump.s) can name them and
get R_68K_32 relocations.  The kernel's C reaches the same hardware through
the macros of arch/m68k/sau2/hw.h (and svc/svc.h for the PROT boundary).
Two spellings of one number: this check keeps them equal.  The table below
is the only place that says which C macro each assembler symbol mirrors;
a symbol with no C macro is listed with None and its value is checked
against the number given here.

    python3 tools/check_iodefs.py          (make check-iodefs)
"""

import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
IODEFS = os.path.join(ROOT, 'arch', 'm68k', 'sau2', 'iodefs.s')

# asm symbol -> (header, C macro) or (None, literal) when C has no name for it
MIRROR = {
    'TRAP_PAGE': (None, 0x00000000),      # the VBR page; arch/m68k/arch.h
                                          # documents it, no C macro names 0
    'PTT':       ('arch/m68k/sau2/hw.h', 'SAU2_PTT_BASE'),
    'PROT':      ('svc/svc.h', 'SVC_USER_SPACE_LIMIT'),  # user space ends
                                          # where the PROT window begins
    'DISP1_MEM': ('arch/m68k/sau2/hw.h', 'SAU2_DISPLAY_MEM_BASE'),
    'DISP1':     ('arch/m68k/sau2/hw.h', 'SAU2_DISPLAY_CTRL_REGS'),
    'RING2':     ('arch/m68k/sau2/hw.h', 'SAU2_RING2_BASE'),
    'DMA':       ('arch/m68k/sau2/hw.h', 'SAU2_DMAC_BASE'),
    'DISK':      ('arch/m68k/sau2/hw.h', 'SAU2_DISK_BASE'),
    'TIMR':      ('arch/m68k/sau2/hw.h', 'SAU2_TIMER_BASE'),
    'SIO':       ('arch/m68k/sau2/hw.h', 'SAU2_SIO_BASE'),
    'MMU':       ('arch/m68k/sau2/hw.h', 'SAU2_MMU_REGS'),
    'PFT':       ('arch/m68k/sau2/hw.h', 'SAU2_PFT_BASE'),
}

EQU_RE = re.compile(r'^\s*\.equ\s+([A-Za-z_$][\w$]*)\s*,\s*(0[xX][0-9A-Fa-f]+|\d+)')
DEFINE_RE = re.compile(r'^\s*#\s*define\s+([A-Za-z_]\w*)\s+(.*)$')
NUMBER_RE = re.compile(r'0[xX][0-9A-Fa-f]+|\b\d+\b')


def asm_symbols(path):
    out = {}
    with open(path) as f:
        for line in f:
            m = EQU_RE.match(line)
            if m:
                out[m.group(1)] = int(m.group(2), 0)
    return out


def header_macros(path):
    out = {}
    with open(path) as f:
        for line in f:
            m = DEFINE_RE.match(line)
            if not m:
                continue
            value = m.group(2).split('/*')[0]
            n = NUMBER_RE.search(value)
            if n:
                out[m.group(1)] = int(n.group(0).rstrip('uUlL'), 0)
    return out


def main():
    syms = asm_symbols(IODEFS)
    headers = {}
    problems = []
    for name, (header, ref) in MIRROR.items():
        if name not in syms:
            problems.append('%s: no .equ in iodefs.s' % name)
            continue
        if header is None:
            want = ref
            where = 'the literal in tools/check_iodefs.py'
        else:
            if header not in headers:
                headers[header] = header_macros(os.path.join(ROOT, header))
            if ref not in headers[header]:
                problems.append('%s: %s defines no numeric %s' % (name, header, ref))
                continue
            want = headers[header][ref]
            where = '%s %s' % (header, ref)
        if syms[name] != want:
            problems.append('%s: iodefs.s 0x%X, %s 0x%X' % (name, syms[name], where, want))
    for name in syms:
        if name not in MIRROR:
            problems.append('%s: in iodefs.s but not in the MIRROR table' % name)
    for p in problems:
        print('check_iodefs: ' + p)
    print('check_iodefs: %d symbol(s), %d problem(s)' % (len(syms), len(problems)))
    return 1 if problems else 0


if __name__ == '__main__':
    sys.exit(main())
